/**
 * GAEILGE – Irish interface text. Must have exactly the same keys as en.ts.
 *
 * Numbers + nouns follow the Irish counting rules via `count()`:
 *   1 → "ceist amháin", 2–6 → séimhiú ("3 cheist"), 7–10 → urú ("7 gceist"), 11+ → "20 ceist".
 *
 * Teachers/native speakers: corrections are very welcome – just edit the strings.
 */
import type { Dict } from './en';

const LENITE = /^([bcdfgmpt]|s(?=[aeiouáéíóúlnr]))(?!h)/i;
const lenite = (w: string) => w.replace(LENITE, (m) => m + 'h');
const ECLIPSE: Record<string, string> = { b: 'm', c: 'g', d: 'n', f: 'bh', g: 'n', p: 'b', t: 'd' };
const eclipse = (w: string) => {
  const c = w[0].toLowerCase();
  if (ECLIPSE[c]) return ECLIPSE[c] + w;
  if (/[aeiouáéíóú]/i.test(c)) return 'n-' + w;
  return w;
};
/** Irish counted noun, e.g. count(3, 'ceist') → "3 cheist". */
export function count(n: number, noun: string): string {
  if (n === 1) return `${noun} amháin`;
  if (n >= 2 && n <= 6) return `${n} ${lenite(noun)}`;
  if (n >= 7 && n <= 10) return `${n} ${eclipse(noun)}`;
  return `${n} ${noun}`;
}

